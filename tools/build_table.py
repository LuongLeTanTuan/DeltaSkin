#!/usr/bin/env python3
"""Rebuild src/SkinTable.h from the vendor binary's own catalog.

The vendored menu keeps two static catalogs of non-default cosmetics in
PxExtFFi. Every row is a 16-byte record:

    u32 appearanceId
    u32 kind          (always 6 here -- the row's type tag)
    u32 nameFileOff   (offset of the display string inside the same binary)
    u32 nameTag       (always 0x00300000 here)

Records are not on a fixed stride (the two catalogs pad differently), so the
only reliable way to read them is to scan for the (kind, nameTag) pair and then
resolve the name. A naive scan also matches bytes inside unrelated data, so this
tool validates each candidate against the chain of its neighbours and drops any
record whose name does not resolve. Those ghosts were the bad ids: they pointed
at no cosmetic, so picking such a row applied whatever the game had at that id.

Grouping is derived from the vendor's own display string ("<weapon> - <skin>")
with an explicit separator class. Strings with no separator are not weapons --
they are melee / cosmetic entries -- and they all land in one bucket instead of
being shown as fifteen fake guns.

Usage:
    python tools/build_table.py            # rewrite src/SkinTable.h
    python tools/build_table.py --check    # exit 1 if the header is stale
"""

import argparse
import collections
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PXFFI = os.environ.get(
    "PXEXTFFI",
    r"D:\delta\Payload\DeltaForceClient.app\Frameworks\PxExtFFi.framework\PxExtFFi",
)
OUT = os.path.join(ROOT, "src", "SkinTable.h")

XOR = 0x5A
KIND = 6
NAME_TAG = 0x00300000
MELEE = "Cận chiến & Khác"
SEP = re.compile(r"^(.*?)\s+[\-\u2010\u2011\u2012\u2013\u2014]\s+(.+)$")

HEADER = """\
// Generated by tools/build_table.py from the vendor catalog in PxExtFFi.
// {weapons} weapon groups / {rows} skins. Do not edit by hand.
//
// Every id below is an appearance id copied verbatim from the vendor's static
// table. Rows whose id could not be resolved to a display name were dropped:
// those are the ids that used to apply a cosmetic belonging to some other row.
//
// Blob layout: {weapons} length-prefixed weapon names, then {rows} rows of
//   {{ u8 weaponIndex, u32 skinId, u8 nameLen, name }}
// all XOR 0x5A.
#define DS_WEAPON_COUNT {weapons}
#define DS_SKIN_ROW_COUNT {rows}
static const unsigned char ds_blob[{size}] = {{
"""


def read_records(path):
    with open(path, "rb") as f:
        data = f.read()
    n = len(data)

    def cstr(off, cap=200):
        if off <= 0 or off >= n:
            return None
        end = data.find(b"\x00", off, off + cap)
        if end < 0:
            return None
        try:
            s = data[off:end].decode("utf8")
        except UnicodeDecodeError:
            return None
        return s or None

    hits = []
    i = 0
    while i + 16 <= n:
        if data[i + 4:i + 8] == struct.pack("<I", KIND) and \
           data[i + 12:i + 16] == struct.pack("<I", NAME_TAG):
            idv = struct.unpack_from("<I", data, i)[0]
            noff = struct.unpack_from("<I", data, i + 8)[0]
            hits.append({"off": i, "id": idv, "name": cstr(noff)})
            i += 16
            continue
        i += 4

    # Keep a record only when its name pointer resolves to a real string.
    # Coincidental byte matches inside unrelated data never do, and the three
    # ghosts that broke the old table all share one dead pointer (0x1CC46B1).
    # Stride is not usable as a filter: the catalogs pad differently (16 vs 24
    # bytes) and the first row of a cluster can sit 0xA8 past the previous one.
    kept = [h for h in hits if h["name"]]
    dropped = [h for h in hits if not h["name"]]
    return kept, dropped


def group(records):
    """Split "<weapon> - <skin>".

    Eight of the vendor strings glue the dash straight onto the weapon name
    ("KC17 Assault Rifle-SAW"). Those are still weapon skins, so a second pass
    re-splits them whenever the prefix is a weapon already seen. Everything
    else without a separator is a melee / cosmetic entry and shares one bucket.
    """
    order = []
    buckets = collections.OrderedDict()
    pending = []
    for r in records:
        full = r["name"].strip()
        m = SEP.match(full)
        if not m:
            pending.append((r["id"], full))
            continue
        weapon, skin = m.group(1).strip(), m.group(2).strip()
        if weapon not in buckets:
            buckets[weapon] = []
            order.append(weapon)
        buckets[weapon].append((r["id"], skin))

    known = set(order)
    melee = []
    for sid, full in pending:
        head, sep, tail = full.rpartition("-")
        if sep and head.strip() in known:
            buckets[head.strip()].append((sid, tail.strip()))
        else:
            melee.append((sid, full))

    if melee:
        order.append(MELEE)
        buckets[MELEE] = melee
    return order, buckets


def encode(order, buckets):
    out = bytearray()
    for w in order:
        b = w.encode("utf8")
        assert len(b) < 256
        out.append(len(b))
        out += b
    rows = 0
    for wi, w in enumerate(order):
        for sid, skin in buckets[w]:
            b = skin.encode("utf8")
            assert len(b) < 256
            out.append(wi)
            out += struct.pack("<I", sid)
            out.append(len(b))
            out += b
            rows += 1
    return out, rows


def render(order, buckets, blob, rows):
    body = []
    for i in range(0, len(blob), 16):
        chunk = blob[i:i + 16]
        body.append("    " + ",".join("0x%02X" % (b ^ XOR) for b in chunk) + ",")
    return HEADER.format(weapons=len(order), rows=rows, size=len(blob)) + \
        "\n".join(body) + "\n};\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    if not os.path.exists(PXFFI):
        sys.exit("vendor binary not found: %s (set PXEXTFFI)" % PXFFI)

    kept, dropped = read_records(PXFFI)
    order, buckets = group(kept)
    blob, rows = encode(order, buckets)
    text = render(order, buckets, blob, rows)

    ids = [s for w in order for s, _ in buckets[w]]
    assert len(ids) == len(set(ids)), "duplicate appearance ids"
    assert len(ids) == rows

    print("records kept    : %d" % len(kept))
    print("records dropped : %d" % len(dropped))
    for d in dropped:
        print("   ghost id %#010x (record %#x, name offset unresolved)"
              % (d["id"], d["off"]))
    print("weapon groups   : %d" % len(order))
    print("skin rows       : %d" % rows)
    print("unique ids      : %d" % len(set(ids)))
    print("blob bytes      : %d" % len(blob))

    if args.check:
        cur = open(OUT, "r", encoding="utf8").read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("src/SkinTable.h is stale -- run tools/build_table.py")
        print("header is up to date")
        return

    with open(OUT, "w", encoding="utf8", newline="\n") as f:
        f.write(text)
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
